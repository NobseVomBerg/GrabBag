"""Build custom_templates/pv_historie.jinja from the actual daily PV yields.

For every calendar day the table holds mean and max of the real daily yield of both
inverters (WR1 + WR2 daily PV generation, long-term statistics) within +-10 days,
over all years available. Days on which one inverter was down are left out. The Forecast.Solar forecast knows nothing about the shading
(buildings, mountains),
so the battery automations cap the forecast at the historical max of the season.

Usage:  python tools/pv_historie.py            -> writes the file into the repo
        python tools/pv_historie.py --upload   -> also uploads it to HA and reloads custom templates
Re-run now and then (at least yearly) so the table contains the latest year.
"""
import datetime as dt
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sync_from_ha import ROOT, call, mcp_url  # noqa: E402

WR1, WR2 = "sensor.daily_pv_generation", "sensor.wr2_daily_pv_generation"
WINDOW = 10
TARGET = "custom_templates/pv_historie.jinja"

try:
    from zoneinfo import ZoneInfo
    TZ = ZoneInfo("Europe/Berlin")
except Exception:  # no tzdata on this machine -> local time (the PC runs in Germany)
    TZ = None


def daily_yields(url, sensor):
    today = dt.date.today()
    out, offset = {}, 0
    while True:
        res = call(url, "ha_get_history", {
            "source": "statistics", "entity_ids": sensor, "start_time": "3000d",
            "period": "day", "statistic_types": ["change"], "limit": 1000, "offset": offset,
        })
        if not res.get("data"):
            sys.exit(f"statistics query failed: {res}")
        ent = res["data"]["entities"][0]
        for r in ent["statistics"]:
            day = dt.datetime.fromtimestamp(r["start"] / 1000, TZ).date()
            if day < today and r.get("change") is not None:
                out[day] = r["change"]
        if not ent.get("has_more"):
            return out
        offset = ent["next_offset"]


def plant_yields(url):
    """Daily yield of both inverters; days where one inverter was down are dropped.

    WR2 was defective from 2024-04-30 to 2024-06-24 and had no data before 2024-03-13;
    such days would pull the table down, so a day only counts when both inverters ran
    (the weaker one delivers at least 50 % of the stronger, normally they are within 10 %).
    """
    w1, w2 = daily_yields(url, WR1), daily_yields(url, WR2)
    out, skipped = {}, []
    for day in sorted(set(w1) | set(w2)):
        a, b = w1.get(day), w2.get(day)
        if a is None or b is None or (max(a, b) > 3 and min(a, b) < 0.5 * max(a, b)):
            skipped.append(day)
            continue
        out[day] = a + b
    return out, skipped


def table(yields):
    years = sorted({d.year for d in yields})
    rows = {}
    for doy in range(366):
        md = dt.date(2024, 1, 1) + dt.timedelta(days=doy)  # leap year -> covers 02-29
        vals = []
        for y in years:
            try:
                center = md.replace(year=y)
            except ValueError:
                center = dt.date(y, 2, 28)
            vals += [yields[d] for i in range(-WINDOW, WINDOW + 1) if (d := center + dt.timedelta(days=i)) in yields]
        if vals:
            rows[md.strftime("%m-%d")] = (round(sum(vals) / len(vals), 1), round(max(vals), 1), len(vals))
    return rows


def render(rows, first, last):
    entries = ",\n    ".join(f"'{k}': [{m}, {x}]" for k, (m, x, _) in sorted(rows.items()))
    return f"""{{#
  Actual daily PV yield of both inverters (kWh) per calendar day: [mean, max] within +-{WINDOW} days.
  GENERATED by tools/pv_historie.py from the long-term statistics of WR1 + WR2 daily PV generation
  ({first} .. {last}, days with an inverter outage left out) - do not edit by hand, re-run the script instead.
  pv_hist(datum) returns JSON {{"mittel": .., "max": ..}} or {{}} when there is no data for that day.
#}}
{{% macro pv_hist(datum) -%}}
{{%- set t = {{
    {entries}
}} -%}}
{{%- set w = t.get(datum.strftime('%m-%d')) -%}}
{{{{- ({{'mittel': w[0], 'max': w[1]}} if w else {{}}) | tojson -}}}}
{{%- endmacro %}}
"""


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    url = mcp_url()
    yields, skipped = plant_yields(url)
    if not yields:
        sys.exit("no statistics found")
    ranges = []
    for day in skipped:
        if ranges and (day - ranges[-1][1]).days <= 3:
            ranges[-1][1] = day
        else:
            ranges.append([day, day])
    print("left out (inverter down or no data):", ", ".join(f"{a}..{b}" if a != b else f"{a}" for a, b in ranges))
    rows = table(yields)
    content = render(rows, min(yields), max(yields))
    (ROOT / TARGET).write_text(content, encoding="utf-8", newline="\n")
    print(f"{TARGET}: {len(rows)} days from {len(yields)} daily values ({min(yields)} .. {max(yields)})")
    for md in ["01-10", "02-10", "03-10", "06-21", "10-15", "11-15", "12-21"]:
        if md in rows:
            print(f"  {md}: mean {rows[md][0]} kWh, max {rows[md][1]} kWh ({rows[md][2]} days)")
    if "--upload" in sys.argv:
        call(url, "ha_write_file", {"path": TARGET, "content": content, "overwrite": True})
        call(url, "ha_call_service", {"domain": "homeassistant", "service": "reload_custom_templates"})
        print("uploaded and custom templates reloaded")


if __name__ == "__main__":
    main()
